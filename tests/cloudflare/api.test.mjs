import test from 'node:test';
import { createECDH } from 'node:crypto';
import assert from 'node:assert/strict';
import { Miniflare, convertV4MiniflareOptions } from 'miniflare';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const planned = { kind: 'date', title: 'Ужин', date: '2026-10-22', time: '19:00', category: 'date', status: 'planned' };
test('Cloudflare SQLite: two partners, authorization, private notes, calendar feed and persistence', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'calendar-cloudflare-'));
  const deliveries = [];
  const options = convertV4MiniflareOptions({ outboundService: async request => { deliveries.push({ url: request.url, authorization: request.headers.get('authorization'), encoding: request.headers.get('content-encoding'), body: Buffer.from(await request.arrayBuffer()) }); return new Response('', { status: 201 }); }, modules: true, scriptPath: '.worker-build/index.js', compatibilityDate: '2026-10-22', compatibilityFlags: ['nodejs_compat'], durableObjects: { CALENDAR: { className: 'CalendarServer', useSQLite: true } }, resourcePersistencePath: dir });
  let mf = new Miniflare(options);
  t.after(async () => { await mf.dispose(); rmSync(dir, { recursive: true, force: true }); });
  function client() { let cookie = ''; return async (path, method = 'GET', body) => {
    const response = await mf.dispatchFetch('https://calendar.example/api' + path, { method, headers: { cookie, ...(body ? { 'Content-Type': 'application/json', Origin: 'https://calendar.example' } : {}) }, body: body ? JSON.stringify(body) : undefined });
    if (response.headers.get('set-cookie')) { assert.match(response.headers.get('set-cookie'), /; Secure/); cookie = response.headers.get('set-cookie').split(';')[0]; }
    const content = response.headers.get('content-type')?.includes('text/calendar') ? await response.text() : await response.json();
    return { status: response.status, data: content };
  }; }
  const a = client(), b = client(), other = client();
  assert.deepEqual((await a('/health')).data, { ok: true });
  assert.equal((await a('/runtime')).data.sync, 'poll');
  assert.equal((await a('/events', 'POST', planned)).status, 401);
  const pair = await a('/pairs', 'POST', { name: 'А' });
  assert.equal(pair.status, 201);
  assert.equal((await b('/join', 'POST', { name: 'Б', invite: pair.data.invite })).status, 200);
  await other('/pairs', 'POST', { name: 'Другая пара' });
  const event = await a('/events', 'POST', planned);
  assert.equal(event.status, 201);
  const id = event.data.id;
  assert.equal((await b('/session')).data.events[0].id, id);
  assert.equal((await other(`/events/${id}/private`)).status, 404);
  await a(`/events/${id}/private`, 'PUT', { note: 'Личное' });
  assert.equal((await b(`/events/${id}/private`)).data.note, '');
  assert.equal((await a(`/events/${id}/private`)).data.note, 'Личное');
  assert.equal((await b(`/events/${id}`, 'PATCH', { ...planned, version: 1, title: 'Новый ужин' })).status, 200);
  assert.equal((await a(`/events/${id}`, 'PATCH', { ...planned, version: 1 })).status, 409);
  const intimacy = await b('/events', 'POST', { kind: 'intimacy', sexType: 'oral', date: '2026-10-23', time: '', status: 'planned', note: 'Не передавать', tags: ['Свечи'] });
  assert.equal(intimacy.status, 201);
  const subscription = await a('/calendar/subscription', 'POST', {});
  assert.equal(subscription.status, 201);
  const feedPath = new URL(subscription.data.url).pathname.replace('/api', '');
  const feed = await a(feedPath);
  assert.match(feed.data, /SUMMARY:Новый ужин/); assert.match(feed.data, /SUMMARY:Время для двоих/);
  assert.doesNotMatch(feed.data, /Не передавать|Личное|Свечи/);
  const push = await a('/push/config'); assert.equal(push.data.enabled, true); assert.ok(push.data.publicKey);
  const ecdh = createECDH('prime256v1'); ecdh.generateKeys();
  const device = { endpoint: 'https://fcm.googleapis.com/fcm/send/test-device', keys: { p256dh: ecdh.getPublicKey().toString('base64url'), auth: Buffer.alloc(16, 7).toString('base64url') } };
  assert.equal((await a('/push/subscriptions', 'POST', device)).status, 201);
  const testPush = await a('/push/test', 'POST', {});
  assert.equal(testPush.status, 200, JSON.stringify(testPush.data));
  assert.equal(deliveries.length, 1);
  assert.match(deliveries[0].authorization, /^vapid /);
  assert.equal(deliveries[0].encoding, 'aes128gcm');
  assert.ok(deliveries[0].body.length > 0);
  assert.ok(!deliveries[0].body.includes(Buffer.from('Уведомления подключены')));
  await a('/push/subscriptions', 'DELETE', { endpoint: device.endpoint });
  const node = (id, type, next) => ({ id, type, next, title: id, body: '', button: 'Дальше', required: true, options: [] });
  const scenario = { title: 'Наш сценарий', theme: 'city-night', start: 'intro', nodes: [node('intro', 'intro', 'when'), { ...node('when', 'datetime', 'accept'), dateMode: 'choose' }, node('accept', 'accept', null)] };
  const draft = await a('/dates/invitations', 'POST', { scenario });
  assert.equal(draft.status, 201);
  assert.equal((await b('/dates/invitations')).data.length, 0);
  const published = await a(`/dates/invitations/${draft.data.id}/publish`, 'POST', { version: 1 });
  assert.equal(published.status, 200);
  const answer = { versionId: published.data.publishedId, answers: { intro: true, when: { date: '2026-10-25', time: '20:00' }, accept: true } };
  assert.equal((await b(`/dates/invitations/${draft.data.id}/respond`, 'POST', answer)).status, 201);
  assert.equal((await b(`/dates/invitations/${draft.data.id}/respond`, 'POST', answer)).status, 200);
  await mf.dispose(); mf = new Miniflare(options);
  assert.equal((await a('/session')).data.events.length, 3);
  assert.deepEqual((await a('/push/config')).data, push.data);
  assert.equal((await a(feedPath)).status, 200);
  await a('/calendar/subscription', 'DELETE', {});
  assert.equal((await a(feedPath)).status, 404);
  assert.equal((await a(`/events/${id}`, 'DELETE', { version: 2 })).status, 200);
  assert.equal((await b('/session')).data.events.length, 2);
  const csrf = await mf.dispatchFetch('https://calendar.example/api/pairs', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://evil.example' }, body: JSON.stringify({ name: 'Bad' }) });
  assert.equal(csrf.status, 403);
});
