import { test, expect } from '@playwright/test';

test('demo calendar, ideas, history and mobile layout', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Время для нас' })).toBeVisible();
  await expect(page.locator('.demo-banner')).toContainText('Демо');
  expect(await page.locator('.calendar-event').count()).toBeGreaterThan(0);
  await page.screenshot({ path: 'test-results/calendar-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Идеи для свиданий', exact: true }).click();
  await expect(page.locator('.atmosphere-card')).toHaveCount(10);
  await page.getByRole('button', { name: 'Настроить свидание', exact: true }).first().click();
  await expect(page.getByLabel('Название свидания', { exact: true })).toHaveValue('На максималках');
  await page.getByRole('button', { name: 'К атмосферам', exact: true }).click();
  await page.getByRole('button', { name: 'Наша история', exact: true }).click();
  await expect(page.locator('.history-event')).toHaveCount(1);
  await page.getByRole('button', { name: 'Наш календарь', exact: true }).click();
  await page.getByRole('button', { name: 'Следующий месяц' }).click();
  await page.getByRole('button', { name: 'Сегодня', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/calendar-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Запланировать свидание', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click();
  expect(errors).toEqual([]);
});

test('two partners share plans live while personal notes remain separate', async ({ browser }) => {
  const first = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const second = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const alice = await first.newPage(), mark = await second.newPage();
  try {
    await alice.goto('/');
    await alice.getByRole('button', { name: 'Создать пару', exact: true }).click();
    await alice.getByLabel('Как вас зовут?').fill('Алиса');
    await alice.getByRole('button', { name: 'Создать общий календарь', exact: true }).click();
    const invite = await alice.getByRole('textbox', { name: 'Ссылка-приглашение' }).inputValue();
    await alice.getByRole('button', { name: 'Закрыть', exact: true }).click();
    await expect(alice.locator('.calendar-event')).toHaveCount(0);
    await mark.goto(invite);
    await mark.getByLabel('Как вас зовут?').fill('Марк');
    await mark.getByRole('button', { name: 'Присоединиться', exact: true }).click();
    await expect(mark.getByRole('dialog')).not.toBeVisible();
    await expect(alice.getByRole('button', { name: 'Наша пара', exact: true })).toBeVisible();
    await alice.getByRole('button', { name: 'Запланировать свидание', exact: true }).click();
    await alice.getByLabel('Название', { exact: true }).fill('Наш особенный ужин');
    await alice.getByLabel('Место', { exact: false }).fill('Дома');
    await alice.getByLabel('Общая заметка', { exact: false }).fill('Готовим вместе');
    await alice.getByRole('checkbox').check();
    await alice.getByLabel('Как назовём?', { exact: true }).fill('Вечер близости');
    await alice.getByLabel('Общие пожелания', { exact: false }).fill('Любимая музыка');
    await alice.getByRole('button', { name: 'Добавить свидание', exact: true }).click();
    await expect(mark.locator('.calendar-event', { hasText: 'Наш особенный ужин' })).toBeVisible();
    await alice.locator('.calendar-event').click();
    await alice.getByRole('textbox', { name: 'Личная заметка', exact: true }).fill('Это только мой секрет');
    await alice.getByRole('button', { name: 'Сохранить личную заметку', exact: true }).click();
    await expect(alice.getByRole('button', { name: 'Сохранено', exact: true })).toBeVisible();
    await mark.locator('.calendar-event').click();
    await expect(mark.getByText('Любимая музыка', { exact: true })).toBeVisible();
    await expect(mark.getByRole('textbox', { name: 'Личная заметка', exact: true })).toHaveValue('');
    await mark.getByRole('textbox', { name: 'Личная заметка', exact: true }).fill('Мой собственный секрет');
    await mark.getByRole('button', { name: 'Сохранить личную заметку', exact: true }).click();
    await expect(mark.getByRole('button', { name: 'Сохранено', exact: true })).toBeVisible();
    await mark.getByRole('button', { name: 'Изменить', exact: true }).click();
    await mark.getByLabel('Название', { exact: true }).fill('Ужин и долгие разговоры');
    await mark.getByRole('button', { name: 'Сохранить изменения', exact: true }).click();
    await alice.getByRole('button', { name: 'Закрыть', exact: true }).click();
    await expect(alice.locator('.calendar-event', { hasText: 'Ужин и долгие разговоры' })).toBeVisible();
    await alice.locator('.calendar-event').click();
    await expect(alice.getByRole('textbox', { name: 'Личная заметка', exact: true })).toHaveValue('Это только мой секрет');
    await alice.getByRole('button', { name: 'Встреча состоялась', exact: true }).click();
    await mark.getByRole('button', { name: 'Наша история', exact: true }).click();
    await expect(mark.locator('.history-event', { hasText: 'Ужин и долгие разговоры' })).toBeVisible();
    await mark.reload();
    await expect(mark.getByRole('button', { name: 'Наша пара', exact: true })).toBeVisible();
    await mark.locator('.calendar-event').click();
    await expect(mark.getByRole('textbox', { name: 'Личная заметка', exact: true })).toHaveValue('Мой собственный секрет');
    await mark.getByRole('button', { name: 'Удалить встречу', exact: true }).click();
    await mark.getByRole('button', { name: 'Удалить', exact: true }).click();
    await expect(alice.locator('.calendar-event')).toHaveCount(0);
  } finally { await first.close(); await second.close(); }
});

test('couple mode syncs independent intimacy facts, private ratings and relationship changes', async ({ browser }) => {
  const first = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const second = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const alice = await first.newPage(), mark = await second.newPage();
  const errors: string[] = [];
  alice.on('pageerror', error => errors.push(error.message));
  mark.on('pageerror', error => errors.push(error.message));
  try {
    await alice.goto('/');
    await alice.getByRole('button', { name: 'Создать пару', exact: true }).click();
    await alice.getByLabel('Как вас зовут?').fill('Алиса');
    await alice.getByRole('button', { name: /Мы пара \/ в браке/ }).click();
    await alice.getByLabel('Название отношений').fill('Супруги');
    await alice.getByRole('button', { name: 'Создать общий календарь', exact: true }).click();
    const invite = await alice.getByRole('textbox', { name: 'Ссылка-приглашение' }).inputValue();
    await alice.getByRole('button', { name: 'Закрыть', exact: true }).click();
    await mark.goto(invite);
    await mark.getByLabel('Как вас зовут?').fill('Марк');
    await mark.getByRole('button', { name: 'Присоединиться', exact: true }).click();
    await expect(mark.locator('.relationship-banner')).toContainText('Супруги');
    await expect(mark.getByTestId('intimacy-facts')).toHaveText('0');
    await mark.getByRole('button', { name: 'Добавить факт', exact: true }).click();
    await expect(mark.getByLabel('Название', { exact: true })).toHaveCount(0);
    await mark.getByLabel('Тип секса', { exact: true }).selectOption('oral');
    await mark.locator('.sex-extras > summary').click();
    await expect(mark.getByRole('textbox', { name: 'Время необязательно', exact: true })).toHaveValue('');
    await mark.getByLabel('Поиск настроений и вариантов').fill('Нежность и массаж');
    await mark.getByRole('button', { name: 'Нежность и массаж', exact: true }).click();
    await mark.getByLabel('Свой вариант', { exact: true }).fill('Наш ритуал');
    await mark.getByRole('button', { name: 'Добавить факт секса', exact: true }).click();
    await expect(alice.locator('.calendar-event', { hasText: 'Оральный секс' })).toBeVisible();
    await expect(alice.getByTestId('intimacy-facts')).toHaveText('1');
    await mark.locator('.calendar-event', { hasText: 'Оральный секс' }).click();
    await mark.getByLabel('Личная оценка').selectOption('5');
    await mark.getByLabel('Личная заметка', { exact: true }).fill('Личное впечатление Марка');
    await mark.getByRole('button', { name: 'Сохранить личную заметку', exact: true }).click();
    await expect(mark.getByRole('button', { name: 'Сохранено', exact: true })).toBeVisible();
    await alice.locator('.calendar-event', { hasText: 'Оральный секс' }).click();
    await expect(alice.getByLabel('Личная оценка')).toHaveValue('');
    await expect(alice.getByLabel('Личная заметка', { exact: true })).toHaveValue('');
    await expect(alice.getByRole('dialog')).toContainText('Наш ритуал');
    await alice.getByRole('button', { name: 'Закрыть', exact: true }).click();
    await mark.getByRole('button', { name: 'Закрыть', exact: true }).click();
    await alice.getByRole('button', { name: 'Запланировать секс', exact: true }).click();
    await alice.getByLabel('Тип секса', { exact: true }).selectOption('vaginal');
    await alice.getByRole('button', { name: 'Добавить план секса', exact: true }).click();
    await expect(mark.getByTestId('intimacy-facts')).toHaveText('1');
    await mark.getByRole('button', { name: '18+', exact: true }).click();
    await expect(mark.locator('.intimacy-plans')).toContainText('Вагинальный секс');
    expect(await mark.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await mark.screenshot({ path: 'test-results/intimacy-mobile.png', fullPage: true });
    await alice.getByRole('button', { name: '18+', exact: true }).click();
    await alice.screenshot({ path: 'test-results/intimacy-desktop.png', fullPage: true });
    await alice.getByRole('button', { name: 'Изменить формат', exact: true }).click();
    await alice.getByRole('button', { name: /Встречаемся/ }).click();
    await alice.getByLabel('Желаемая частота секса').selectOption('3');
    await alice.getByRole('button', { name: 'Сохранить формат', exact: true }).click();
    await expect(mark.locator('.relationship-banner')).toContainText('Встречаемся');
    await expect(mark.locator('.frequency-setting')).toContainText('3 в неделю');
    await mark.reload();
    await expect(mark.locator('.relationship-banner')).toContainText('Встречаемся');
    await mark.getByRole('button', { name: '18+', exact: true }).click();
    await expect(mark.getByTestId('intimacy-facts')).toHaveText('1');
    await mark.getByRole('button', { name: 'Наша история', exact: true }).click();
    await mark.getByRole('group', { name: 'Фильтр истории' }).getByRole('button', { name: 'Секс', exact: true }).click();
    await mark.locator('.history-event', { hasText: 'Оральный секс' }).click();
    await expect(mark.getByLabel('Личная оценка')).toHaveValue('5');
    await expect(mark.getByLabel('Личная заметка', { exact: true })).toHaveValue('Личное впечатление Марка');
    expect(errors).toEqual([]);
  } finally { await first.close(); await second.close(); }
});
