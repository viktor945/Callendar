import { test, expect } from '@playwright/test';

test('archived date module: private draft, deep editable branches, live partner answer and distinct calendar kinds', async ({ browser }) => {
  test.setTimeout(90000);
  const first = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const second = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const alice = await first.newPage(), mark = await second.newPage();
  const errors: string[] = [];
  for (const page of [alice, mark]) page.on('pageerror', error => errors.push(error.message));
  try {
    const created = await first.request.post('/api/pairs', { data: { name: 'Алиса' } });
    const pair = await created.json();
    await second.request.post('/api/join', { data: { name: 'Марк', invite: pair.invite } });
    await alice.goto('/'); await mark.goto('/');
    for (const page of [alice, mark]) await page.getByRole('button', { name: 'Идеи для свиданий', exact: true }).click();
    await expect(alice.locator('.atmosphere-card')).toHaveCount(10);
    await mark.getByRole('tab', { name: /Входящие/ }).click();
    await alice.locator('.atmosphere-card', { hasText: 'Город не спит' }).getByRole('button', { name: 'Настроить свидание' }).click();
    await alice.getByLabel('Название свидания', { exact: true }).fill('Наш ночной маршрут');
    await alice.locator('.scenario-pages button', { hasText: 'Откуда посмотрим на Алматы?' }).click();
    await alice.getByRole('button', { name: 'Добавить этап этой ветки', exact: true }).first().click();
    await alice.getByRole('combobox', { name: 'Тип страницы', exact: true }).selectOption('single');
    await alice.getByLabel('Заголовок страницы').fill('Когда начнём прогулку?');
    await alice.getByLabel('Вариант 1', { exact: true }).fill('На закате');
    await alice.getByRole('button', { name: 'Добавить этап этой ветки', exact: true }).click();
    await alice.getByRole('combobox', { name: 'Тип страницы', exact: true }).selectOption('single');
    await alice.getByLabel('Заголовок страницы').fill('Что возьмём с собой?');
    await alice.getByLabel('Вариант 1', { exact: true }).fill('Термос');
    await alice.getByRole('button', { name: 'Сохранить черновик', exact: true }).click();
    await expect(alice.getByText('Черновик сохранён', { exact: true })).toBeVisible();
    await expect(mark.locator('.invitation-card')).toHaveCount(0);
    await alice.getByRole('button', { name: 'К атмосферам', exact: true }).click();
    await alice.getByRole('tab', { name: /Созданные/ }).click();
    await expect(alice.locator('.invitation-card')).toContainText('Черновик');
    await alice.reload();
    await alice.getByRole('button', { name: 'Идеи для свиданий', exact: true }).click();
    await alice.getByRole('tab', { name: /Созданные/ }).click();
    await alice.getByRole('button', { name: 'Редактировать', exact: true }).click();
    await expect(alice.locator('.scenario-pages')).toContainText('Что возьмём с собой?');
    await alice.getByRole('button', { name: 'Отправить приглашение', exact: true }).click();
    await expect(alice.locator('.invitation-card')).toContainText('Ждёт ответа');
    await expect(mark.locator('.invitation-card')).toContainText('Наш ночной маршрут');
    await mark.getByRole('button', { name: 'Открыть приглашение', exact: true }).click();
    await mark.getByRole('button', { name: 'Да, я в деле', exact: true }).click();
    await mark.locator('.stage-action').click();
    await mark.getByRole('button', { name: /Кок-Тобе/ }).click(); await mark.locator('.stage-action').click();
    await expect(mark.locator('.date-theme')).toHaveAttribute('data-theme', 'city-night');
    await expect(mark.getByRole('heading', { name: 'Когда начнём прогулку?' })).toBeVisible();
    await mark.getByRole('button', { name: /На закате/ }).click(); await mark.locator('.stage-action').click();
    await mark.getByRole('button', { name: /Термос/ }).click(); await mark.locator('.stage-action').click();
    await mark.getByRole('button', { name: /Встретить закат/ }).click();
    await mark.getByRole('button', { name: /Встретить закат/ }).click(); // An empty required choice must not crash the player.
    await expect(mark.locator('.stage-action')).toBeDisabled();
    await mark.getByRole('button', { name: /Встретить закат/ }).click(); await mark.locator('.stage-action').click();
    await mark.getByLabel('Дата', { exact: true }).fill('');
    await mark.getByLabel('Дата', { exact: true }).fill('2026-10-20');
    for (let i = 0; i < 4; i++) await mark.getByRole('button', { name: 'Назад', exact: true }).click();
    await mark.getByRole('button', { name: /Арбат/ }).click(); await mark.locator('.stage-action').click();
    await expect(mark.getByRole('heading', { name: /Арбат: что будем делать/ })).toBeVisible();
    await mark.getByRole('button', { name: /Вечерняя прогулка/ }).click(); await mark.locator('.stage-action').click();
    await mark.getByLabel('Дата', { exact: true }).fill('2026-10-20'); await mark.locator('.stage-action').click();
    await mark.getByLabel('Ваш ответ').fill('Зайдём за кофе'); await mark.locator('.stage-action').click();
    await expect(mark.locator('.stage-summary')).toContainText('Арбат');
    await expect(mark.locator('.stage-summary')).not.toContainText('Термос');
    await mark.screenshot({ path: 'test-results/date-invitation-mobile.png', fullPage: true });
    expect(await mark.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await mark.getByRole('button', { name: 'Принять приглашение', exact: true }).click();
    await expect(mark.getByText('Свидание принято', { exact: true })).toBeVisible();
    await expect(alice.locator('.response-summary')).toContainText('Зайдём за кофе');
    await expect(alice.locator('.response-summary')).not.toContainText('Термос');
    await alice.getByRole('button', { name: 'Открыть свидание в календаре', exact: true }).click();
    await expect(alice.getByRole('dialog')).toContainText('Арбат');
    await alice.getByRole('button', { name: 'Закрыть', exact: true }).click();
    await alice.getByRole('button', { name: 'Запланировать свидание', exact: true }).click();
    await alice.getByRole('group', { name: 'Тип встречи' }).getByRole('button', { name: 'Близость', exact: true }).click();
    await alice.getByLabel('Название', { exact: true }).fill('Отдельный интимный план');
    await alice.getByRole('button', { name: 'Добавить план близости', exact: true }).click();
    await alice.getByRole('group', { name: 'Фильтр календаря' }).getByRole('button', { name: /Все встречи/ }).click();
    await expect(alice.locator('.calendar-event.kind-date')).toHaveCount(1);
    await expect(alice.locator('.calendar-event.kind-intimacy')).toHaveCount(1);
    const dateColor = await alice.locator('.calendar-event.kind-date').evaluate(el => getComputedStyle(el).backgroundColor);
    const intimacyColor = await alice.locator('.calendar-event.kind-intimacy').evaluate(el => getComputedStyle(el).backgroundColor);
    expect(dateColor).not.toBe(intimacyColor);
    await expect(alice.locator('.calendar-event.kind-date')).toHaveAttribute('aria-label', /Свидание · Запланировано/);
    await expect(alice.locator('.calendar-event.kind-intimacy')).toHaveAttribute('aria-label', /Близость · Запланировано/);
    await alice.screenshot({ path: 'test-results/calendar-two-kinds.png', fullPage: true });
    expect(errors).toEqual([]);
  } finally { await first.close(); await second.close(); }
});
